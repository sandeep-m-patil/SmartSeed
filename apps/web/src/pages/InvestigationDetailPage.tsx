import { useQuery } from '@tanstack/react-query';
import { Link, useParams } from 'react-router-dom';
import { useApi } from '../hooks/useApi';
import { useRoles } from '../hooks/useMe';
import { formatDateTime, titleCase } from '../lib/format';
import type { FindingKind, Investigation } from '../types';
import { Badge, StatusBadge, type Tone } from '../components/Badge';
import { InvestigationActions } from '../components/InvestigationActions';
import { Card, PageHeader } from '../components/Layout';
import { QueryState } from '../components/QueryState';
import { RiskBadge } from '../components/RiskBadge';

const KIND: Record<FindingKind, { label: string; tone: Tone; help: string }> = {
  observed_fact: { label: 'Observed fact', tone: 'success', help: 'Directly present in platform records' },
  model_interpretation: { label: 'Model interpretation', tone: 'info', help: 'Inferred by the analysis model from the facts' },
  hypothesis: { label: 'Hypothesis', tone: 'warning', help: 'Unverified possibility - needs confirmation' },
};

function Findings({ findings }: { findings: Investigation['report']['findings'] }) {
  return (
    <ul className="space-y-3">
      {findings.map((f, i) => (
        <li key={i} className="rounded-md border border-slate-200 p-3">
          <div className="flex flex-wrap items-center gap-2">
            <Badge tone={KIND[f.kind]?.tone ?? 'neutral'} title={KIND[f.kind]?.help}>{KIND[f.kind]?.label ?? titleCase(f.kind)}</Badge>
          </div>
          <p className="mt-1 text-sm text-slate-800">{f.text}</p>
          {f.evidenceRefs.length > 0 && <p className="mt-1 break-all text-xs text-slate-500">Evidence: {f.evidenceRefs.join(', ')}</p>}
        </li>
      ))}
    </ul>
  );
}

function Report({ inv }: { inv: Investigation }) {
  const r = inv.report;
  return (
    <div className="space-y-4">
      {inv.requiresHumanReview && (
        <div role="note" className="rounded-md border border-blue-300 bg-blue-50 p-3 text-sm text-blue-900">
          This report was generated by {inv.generatedBy}. It requires human review before any action is taken, and it is not a verdict.
        </div>
      )}
      <Card title="Summary">
        <div className="flex flex-wrap items-center gap-2"><RiskBadge score={r.riskScore} /><Badge>{titleCase(r.riskCategory)}</Badge><StatusBadge status={inv.status} /></div>
        <p className="mt-2 text-sm text-slate-800">{r.mainSuspiciousActivity}</p>
      </Card>
      <Card title="Findings">
        {(r.droppedFindings ?? 0) > 0 && <p role="note" className="mb-3 rounded-md bg-yellow-50 px-3 py-2 text-sm text-yellow-900">{r.droppedFindings} generated finding(s) were removed by the server because they were not supported by evidence.</p>}
        <Findings findings={r.findings} />
      </Card>
      <Card title="Timeline">
        {r.timeline.length === 0 ? <p className="text-sm text-slate-500">No timeline entries.</p> : (
          <ol className="space-y-2 border-l-2 border-slate-200 pl-4">
            {r.timeline.map((t, i) => <li key={i} className="text-sm"><time className="text-xs text-slate-500">{formatDateTime(t.at)}</time><p>{t.event}</p><p className="break-all text-xs text-slate-500">{t.ref}</p></li>)}
          </ol>
        )}
      </Card>
      <Card title="Potential explanation"><p className="text-sm text-slate-800">{r.potentialExplanation}</p></Card>
      <Card title="Recommended steps"><ol className="list-decimal space-y-1 pl-5 text-sm text-slate-800">{r.recommendedSteps.map((s, i) => <li key={i}>{s}</li>)}</ol></Card>
      <Card title="Confidence and limitations"><p className="text-sm text-slate-800">{r.confidenceAndLimitations}</p></Card>
    </div>
  );
}

export function InvestigationDetailPage() {
  const { id } = useParams();
  const api = useApi();
  const { can } = useRoles();
  const q = useQuery({ queryKey: ['investigation', id], queryFn: () => api.get<Investigation>(`/v1/investigations/${id}`), enabled: Boolean(id) });
  const inv = q.data;
  return (
    <div className="space-y-4">
      <PageHeader title="Investigation" subtitle={inv ? `Batch ${inv.batchId}` : undefined} actions={<Link to="/investigations" className="text-sm text-brand-700 underline">Back to investigations</Link>} />
      <QueryState isLoading={q.isLoading} error={q.error} isOptionalEndpoint onRetry={() => void q.refetch()}>
        {inv && (
          <>
            {can('investigation:decide') && <Card title="Decide"><InvestigationActions investigationId={inv.id} /></Card>}
            <Report inv={inv} />
            {inv.evidence && inv.evidence.length > 0 && <Card title="Evidence"><ul className="space-y-1 text-sm">{inv.evidence.map((e, i) => <li key={i}><Badge>{titleCase(e.kind)}</Badge> {e.summary}</li>)}</ul></Card>}
            <Card title="Action history">
              {inv.actions.length === 0 ? <p className="text-sm text-slate-500">No actions recorded yet.</p> : (
                <ul className="space-y-2 text-sm">{inv.actions.map((a, i) => <li key={i}><strong>{titleCase(a.action)}</strong> by {a.actorName} <span className="text-xs text-slate-500">{formatDateTime(a.createdAt)}</span>{a.note && <p className="text-slate-700">{a.note}</p>}</li>)}</ul>
              )}
            </Card>
          </>
        )}
      </QueryState>
    </div>
  );
}
